/**
 * whale-refined atlas geometry guard (issue #2021).
 *
 * The built-in `whale-girl-refined` pet draws from
 * `assets/whale-refined/spritesheet.webp`: one 1536x1872 atlas, 8 columns x 9
 * rows of 192x208 cells in `PET_ROW_ORDER`. Issue #2021 repainted the two run
 * rows (row 1 running-right, row 2 running-left) because a far-side cuff and
 * hand sat on the dress at the waist and read as a third arm once a cell scaled
 * down to the 148x160 the pet renders at. Row 2 is now the exact per-cell
 * horizontal mirror of row 1, which is only true while both rows ship one frame
 * per column and the same cadence.
 *
 * What is left for a dependency-free checkout to assert is the geometry half of
 * that contract, from the file header and the manifest:
 *
 * - the canvas is a whole 8x9 grid of 192x208 cells, with no trimmed or padded
 *   margin. The client derives every frame offset from `scaledCellSize` and
 *   `framePosition`, so a re-export at another cell size silently shows the
 *   wrong rectangle of the atlas rather than failing;
 * - the run rows keep one frame per column and one shared cadence, so the
 *   mirror stays 1:1 frame by frame;
 * - the container stays lossless WebP with its alpha channel encoded, because
 *   the transparent padding around each pose is what keeps a 192x208 cell from
 *   bleeding the neighbouring frame into the sprite box.
 *
 * The pixel-level half (every row other than 1 and 2 unchanged, row 2 the exact
 * mirror of row 1) was verified against the pre-fix atlas with an external
 * decoder while the repaint landed; see
 * `.agents/notes/implemented/bug-fix/2026-11-06-whale-refined-third-arm-in-run-rows.md`.
 * @module @linxin666/dsh-pet/tests/whale-refined-atlas
 */

import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { imageDimensions } from '../src/image-dimensions.ts'
import { DEFAULT_PET_CELL, PET_ROW_ORDER, loadPetRegistry, petPackageRoot } from '../src/registry.ts'

const PACKAGE_ROOT = petPackageRoot(import.meta.url)
const ASSET_DIR = join(PACKAGE_ROOT, 'assets', 'whale-refined')

/** The refined whale-girl entry as the runtime resolves it from `assets/`. */
function whaleRefined() {
  const registry = loadPetRegistry({ packageRoot: PACKAGE_ROOT, petsDir: '', dshPetsDir: '' })
  const entry = registry.byId('whale-girl-refined')
  expect(entry).toBeDefined()
  return entry!
}

/** Row index of one animation in the atlas. */
const rowOf = (animation: (typeof PET_ROW_ORDER)[number]): number => PET_ROW_ORDER.indexOf(animation)

describe('whale-refined atlas geometry', () => {
  const entry = whaleRefined()

  it('keeps the canvas a whole 8 x 9 grid of default cells', () => {
    // Given the shipped atlas; when only its header is read; then it is the
    // 1536x1872 canvas eight 192-wide columns by nine 208-tall rows fill exactly.
    const dims = imageDimensions(readFileSync(join(ASSET_DIR, 'spritesheet.webp')))
    expect(dims).toEqual({ width: 1536, height: 1872 })
    expect(entry.cell).toEqual(DEFAULT_PET_CELL)
    expect(dims!.width % entry.cell.width).toBe(0)
    expect(dims!.height % entry.cell.height).toBe(0)
    expect(dims!.width / entry.cell.width).toBe(entry.columns)
    expect(dims!.height / entry.cell.height).toBe(entry.atlasRows)
    // No trimmed or padded canvas: what the cells cover is the whole image.
    expect(entry.columns * entry.cell.width).toBe(dims!.width)
    expect(entry.atlasRows * entry.cell.height).toBe(dims!.height)
  })

  it('keeps the manifest on the default cell instead of rescaling the repaint', () => {
    // A repaint must not smuggle in a `cell` override: that would rescale every
    // row, not just the two that were repainted.
    const manifest = JSON.parse(readFileSync(join(ASSET_DIR, 'pet.json'), 'utf8'))
    expect(manifest.sprite2d.cell).toBeUndefined()
    expect(manifest.sprite2d.spritesheetPath).toBe('spritesheet.webp')
    expect(manifest.sprite2d.frames.length).toBe(entry.atlasRows)
  })

  it('ships one frame per column in both run rows so the mirror is frame for frame', () => {
    // Row 2 is generated by mirroring row 1 cell by cell; that pairing only
    // holds when both rows fill every column.
    expect(entry.rows[rowOf('running-right')]).toBe(entry.columns)
    expect(entry.rows[rowOf('running-left')]).toBe(entry.columns)
    expect(entry.tracks['running-left'].durations)
      .toEqual(entry.tracks['running-right'].durations)
  })

  it('declares no track longer than the row it plays from', () => {
    // An over-long duration list is trimmed at render time, which would leave
    // the mirrored pair with a different visible length.
    for (const [index, animation] of PET_ROW_ORDER.entries()) {
      expect(entry.tracks[animation].durations.length).toBeLessThanOrEqual(entry.rows[index]!)
    }
    expect(entry.rows.length).toBe(entry.atlasRows)
    for (const count of entry.rows) {
      expect(count).toBeGreaterThanOrEqual(1)
      expect(count).toBeLessThanOrEqual(entry.columns)
    }
  })

  it('keeps the lossless container and its encoded alpha channel', () => {
    // Given the repainted atlas; when its RIFF and VP8L headers are read; then
    // the canvas is still lossless with alpha, so the transparent padding
    // around each pose survives the write.
    const buf = readFileSync(join(ASSET_DIR, 'spritesheet.webp'))
    expect(buf.toString('ascii', 0, 4)).toBe('RIFF')
    expect(buf.toString('ascii', 8, 12)).toBe('WEBP')
    expect(buf.toString('ascii', 12, 16)).toBe('VP8L')
    expect(buf[20]).toBe(0x2f)
    const header = buf.readUInt32LE(21)
    // 14-bit width, 14-bit height, one alpha-is-used bit, three version bits.
    expect(1 + (header & 0x3fff)).toBe(1536)
    expect(1 + ((header >>> 14) & 0x3fff)).toBe(1872)
    expect((header >>> 28) & 1).toBe(1)
    expect((header >>> 29) & 7).toBe(0)
  })
})
